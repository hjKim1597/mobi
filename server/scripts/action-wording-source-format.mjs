const MODEL = '@cf/myshell-ai/melotts';
const LANGUAGE = 'kr';
const VERSION = 'action-wording-v1';
const RESAMPLE = 'ffmpeg libswresample (filter_size=64, cutoff=0.95): mono PCM16, 44100 Hz to 16000 Hz';

export function parseEmbeddedActionWording(source) {
  const match = /^export const actionWordingAssets = ([\s\S]+?) as const;$/m.exec(source);
  if (!match) throw new Error('Missing embedded action wording assets');
  try { return JSON.parse(match[1]); }
  catch { throw new Error('Invalid embedded action wording metadata'); }
}

export function renderActionWordingSource(assets) {
  const keys = Object.keys(assets).map(id => JSON.stringify(id));
  return `// Generated by scripts/generate-action-wording-audio.mjs; explicit regeneration only.\n`
    + Object.values(assets).map(asset => `// Model: ${MODEL}; lang: ${LANGUAGE}; version: ${VERSION}; source attempt: ${asset.sourceAttempt}; source SHA-256: ${asset.sourceSha256}; resample: ${RESAMPLE}.`).join('\n') + '\n'
    + `export type ActionWordingAsset = { model: string; lang: string; version: string; text: string; data: string; sha256: string; sampleRate: number; sourceAttempt: number; sourceSha256: string; sourceSampleRate: number; resample: string };\n`
    + `export type ActionWordingSentence = { text: string; audio: { data: string; mimeType: 'audio/wav' } };\n`
    + `export const actionWordingAssets = ${JSON.stringify(assets)} as const;\n`
    + `export const actionWordingSentences = [${keys.map(id => `{ text: actionWordingAssets[${id}].text, audio: { data: actionWordingAssets[${id}].data, mimeType: 'audio/wav' as const } }`).join(', ')}];\n`;
}

export function validateActionWordingSource(source, expectedTexts) {
  const assets = parseEmbeddedActionWording(source);
  if (source !== renderActionWordingSource(assets)) throw new Error('Noncanonical action wording source or sentence mapping');
  if (Object.keys(assets).sort().join() !== Object.keys(expectedTexts).sort().join()) throw new Error('Wrong action wording asset inventory');
  for (const [id, text] of Object.entries(expectedTexts)) {
    const asset = assets[id];
    if (!asset || asset.model !== MODEL || asset.lang !== LANGUAGE || asset.version !== VERSION || asset.text !== text
        || asset.sampleRate !== 16000 || ![1, 2].includes(asset.sourceAttempt) || asset.sourceSampleRate !== 44100
        || asset.resample !== RESAMPLE || !/^[a-f0-9]{64}$/.test(asset.sha256 ?? '')
        || !/^[a-f0-9]{64}$/.test(asset.sourceSha256 ?? '') || typeof asset.data !== 'string') {
      throw new Error(`Wrong action wording provenance or metadata for ${id}`);
    }
    const provenance = `Model: ${MODEL}; lang: ${LANGUAGE}; version: ${VERSION}; source attempt: ${asset.sourceAttempt}; source SHA-256: ${asset.sourceSha256}; resample: ${RESAMPLE}.`;
    if (!source.includes(provenance)) throw new Error(`Missing MeloTTS provenance for ${id}`);
  }
  return assets;
}
